def _discover_local_apps():
    """Auto-discover installed DM apps by scanning for directories with apps.py."""
    from django.apps import AppConfig as _AppConfig
    _skip = {
        'api', 'core', 'demo', 'console', 'generic_storage', 'sdc4_shared',
        'templates', 'staticfiles', 'mediafiles', 'ontologies',
        Path(__file__).resolve().parent.name,  # project config package
    }
    discovered = []
    for entry in sorted(BASE_DIR.iterdir()):
        if not entry.is_dir() or entry.name in _skip:
            continue
        if entry.name.startswith('.') or entry.name.startswith('_'):
            continue
        if not (entry / 'apps.py').exists():
            continue
        try:
            mod = importlib.import_module(f'{entry.name}.apps')
            if any(
                isinstance(getattr(mod, attr, None), type)
                and issubclass(getattr(mod, attr), _AppConfig)
                and getattr(mod, attr) is not _AppConfig
                for attr in dir(mod)
            ):
                discovered.append(entry.name)
        except Exception:
            pass
    return discovered


